#!/usr/bin/env python3
"""Compile-time baseline for R6: the corpus total and the self-host.

Two numbers describe how long R6 takes to build the pinned corpus and the
compiler that reproduces the canonical C. Both are wall time on the machine
that runs the script; the file records which machine.

    python tests/perf/run_perf.py --r6 .r6-build/r6.exe \\
        --selfhost-script scripts/selfhost.ps1 \\
        --orbit-root C:/Temp/orbit-pin-01e31e8-git \\
        --compiler C:/Temp/orbit-fp-ee60c8af43.exe \\
        --check

`--write-baseline` replaces tests/perf/baseline.json for the host platform.
`--check` fails when a total grows past its baseline by more than the
tolerance. A smaller total always passes. It is a measurement, not a gate.
The corpus IR is regenerated by tests/corpus/run_corpus.py; this script only
builds it. The driver, the IR and the runtime archives are copied into the host
temporary directory, so the measured builds read them from local storage rather
than from a shared folder.
"""

import argparse
import json
import os
import shutil
import subprocess
import sys
import tempfile
import time
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
BASELINE = Path(__file__).resolve().with_name("baseline.json")
DEFAULT_TOLERANCE = 0.03


def platform_key():
    return "win64" if os.name == "nt" else "linux-x64"


def default_selfhost_script():
    return REPO / ("scripts/selfhost.ps1" if os.name == "nt" else "scripts/selfhost.sh")


def corpus_programs(ir_dir: Path):
    manifest = ir_dir / "manifest.json"
    if manifest.is_file():
        files = [ir_dir / entry["ir"]
                 for entry in json.loads(manifest.read_text(encoding="utf-8"))["files"]
                 if entry["kind"] == "executable"]
    else:
        files = sorted(p for p in ir_dir.rglob("*.ir") if p.is_file())
    missing = [str(p) for p in files if not p.is_file()]
    if missing:
        sys.exit(f"missing from {ir_dir}: {', '.join(missing[:3])}")
    if not files:
        sys.exit(f"no executable .ir files under {ir_dir}: run tests/corpus/run_corpus.py first")
    return files


def run(cmd, cwd, timeout, env=None):
    return subprocess.run(cmd, cwd=str(cwd), capture_output=True, text=True,
                          timeout=timeout, env=env)


def build_once(r6, source: Path, exe: Path, timeout, env):
    """Wall time and R6's own stage time (load..object, link excluded)."""
    start = time.perf_counter()
    proc = run([str(r6), "build", str(source), "-o", str(exe)], REPO, timeout,
               env=env)
    elapsed = (time.perf_counter() - start) * 1000.0
    if proc.returncode != 0 or not exe.is_file():
        detail = (proc.stderr or proc.stdout).strip()[-400:]
        sys.exit(f"r6 failed on {source} (rc={proc.returncode}): {detail}")
    stages = 0.0
    for line in proc.stderr.splitlines():
        fields = line.split()
        if len(fields) >= 5 and fields[1] == "timing" and fields[2] != "ld":
            stages += float(fields[3])
    return elapsed, stages


def stage(paths, scratch: Path, prefix):
    """Copy inputs to the host temp dir: a shared folder would be measured."""
    staged = []
    for index, source in enumerate(paths):
        target = scratch / f"{prefix}-{index:04d}.ir"
        shutil.copyfile(source, target)
        staged.append(target)
    return staged


def stage_runtime(runtime_dir: Path, scratch: Path):
    """Copy the runtime archives beside the staged IR.

    On Linux the linker reads the archive, and a checkout under /mnt/c puts
    the hypervisor's read path inside every link: 61.6 ms against 18.5 ms for
    the same link with the archive on ext4. Returns the new directory, or
    None when there is no archive to stage.
    """
    archives = [runtime_dir / name for name in ("libruntime_net.a", "libruntime_net_db.a",
                                               "sqlite3.lib")]
    archives = [path for path in archives if path.is_file()]
    if not archives:
        return None
    target_dir = scratch / "runtime"
    target_dir.mkdir()
    for path in archives:
        shutil.copyfile(path, target_dir / path.name)
    return target_dir


def measure_corpus(r6, programs, scratch, reps, timeout, env):
    totals, stages = [], []
    for rep in range(reps):
        total = pipeline = 0.0
        for index, source in enumerate(programs):
            spent, stage_ms = build_once(r6, source,
                                         scratch / f"corpus-{rep}-{index}{exe_suffix()}", timeout,
                                         env)
            total += spent
            pipeline += stage_ms
        totals.append(total)
        stages.append(pipeline)
        print(f"  corpus rep {rep + 1}/{reps}: {total:.0f} ms wall, "
              f"{pipeline:.0f} ms in R6", flush=True)
    return min(totals), min(stages)


def measure_selfhost_r6(r6, ir: Path, scratch, reps, timeout, env):
    times, stages = [], []
    for rep in range(reps):
        spent, stage_ms = build_once(r6, ir, scratch / f"selfhost-{rep}{exe_suffix()}", timeout, env)
        times.append(spent)
        stages.append(stage_ms)
        print(f"  self-host R6 build rep {rep + 1}/{reps}: {spent:.0f} ms wall, "
              f"{stage_ms:.0f} ms in R6", flush=True)
    return min(times), min(stages)


def measure_selfhost_wall(script: Path, orbit_root, compiler, r6, reps, timeout):
    if os.name == "nt":
        cmd = ["powershell.exe", "-NoProfile", "-ExecutionPolicy", "Bypass",
               "-File", str(script), "-OrbitRoot", str(orbit_root),
               "-Compiler", str(compiler), "-R6", str(r6)]
    else:
        cmd = ["bash", str(script), str(orbit_root), str(compiler), str(r6)]
    times = []
    for rep in range(reps):
        start = time.perf_counter()
        proc = run(cmd, REPO, timeout)
        elapsed = (time.perf_counter() - start) * 1000.0
        if proc.returncode != 0 or "SELFHOST OK" not in (proc.stdout + proc.stderr):
            detail = (proc.stderr or proc.stdout).strip()[-600:]
            sys.exit(f"the self-host script did not reach SELFHOST OK: {detail}")
        times.append(elapsed)
        print(f"  self-host wall rep {rep + 1}/{reps}: {elapsed:.0f} ms", flush=True)
    return min(times)


def exe_suffix():
    return ".exe" if os.name == "nt" else ""


def load_baseline(path: Path):
    if not path.is_file():
        return {"platforms": {}}
    return json.loads(path.read_text(encoding="utf-8"))


def compare(measured, was, tolerance):
    """Ratchet the R6-owned totals tightly; the walls move with the machine.

    GNU ld takes 73% of each corpus build on the Linux host, and the same ld
    invocation measured 13 ms warm against 90 ms with a cold page cache, so a
    wall below 15% of noise would fail on an idle change.
    """
    findings = []
    for key, label, slack in (("corpusPipelineMs", "corpus in R6", tolerance),
                              ("selfhostPipelineMs", "self-host in R6", tolerance),
                              ("selfhostR6Ms", "self-host R6 build", max(tolerance, 0.05)),
                              ("corpusTotalMs", "corpus total", max(tolerance, 0.15)),
                              ("selfhostWallMs", "self-host wall", max(tolerance, 0.15))):
        if was.get(key) is None or measured.get(key) is None:
            continue
        limit = was[key] * (1.0 + slack)
        if measured[key] > limit:
            findings.append(f"{label}: {measured[key]:.0f} ms > {limit:.0f} ms "
                            f"(baseline {was[key]:.0f} ms)")
    return findings


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--r6", required=True, help="driver binary")
    parser.add_argument("--ir-dir", default=str(REPO / ".r6-build" / "corpus-ir"),
                        help="corpus IR directory (default .r6-build/corpus-ir)")
    parser.add_argument("--selfhost-ir", default=str(REPO / ".r6-build" / "selfhost" / "main.ir"),
                        help="IR of compiler/host/main.orb (default .r6-build/selfhost/main.ir)")
    parser.add_argument("--selfhost-script", default=str(default_selfhost_script()))
    parser.add_argument("--orbit-root", required=True)
    parser.add_argument("--compiler", required=True)
    parser.add_argument("--reps", type=int, default=3,
                        help="repetitions of the per-build measurements (default 3)")
    parser.add_argument("--wall-reps", type=int, default=1,
                        help="repetitions of the whole self-host script (default 1)")
    parser.add_argument("--timeout", type=int, default=900)
    parser.add_argument("--baseline", default=str(BASELINE))
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--write-baseline", action="store_true")
    parser.add_argument("--tolerance", type=float, default=DEFAULT_TOLERANCE)
    parser.add_argument("--runtime-dir",
                        help="runtime archives (default: R6_RUNTIME_DIR, else "
                             ".r6-build/runtime-<host> under the repository)")
    parser.add_argument("--json", help="write this run's record here")
    args = parser.parse_args()

    r6 = Path(args.r6).resolve()
    if not r6.is_file():
        parser.error(f"no driver at {r6}")
    ir_dir = Path(args.ir_dir).resolve()
    selfhost_ir = Path(args.selfhost_ir).resolve()
    if not selfhost_ir.is_file():
        parser.error(f"no self-host IR at {selfhost_ir}; run scripts/selfhost"
                     f"{'.ps1' if os.name == 'nt' else '.sh'} first")
    script = Path(args.selfhost_script).resolve()

    programs = corpus_programs(ir_dir)
    key = platform_key()
    print(f"platform {key}, driver {r6}, {len(programs)} corpus programs", flush=True)

    scratch = Path(tempfile.mkdtemp(prefix="r6-perf-"))
    try:
        # The driver is an input too: under /mnt/c, exec measured 7.6 ms
        # against 0.5 ms from ext4, and a build pays that once per program.
        staged_r6 = scratch / f"r6{exe_suffix()}"
        shutil.copyfile(r6, staged_r6)
        staged_r6.chmod(0o755)
        runtime_dir = Path(args.runtime_dir or os.environ.get("R6_RUNTIME_DIR")
                           or REPO / ".r6-build" / f"runtime-{key}").resolve()
        runtime_staged = stage_runtime(runtime_dir, scratch)
        if runtime_staged is None:
            print(f"no runtime archive in {runtime_dir}; the driver's default applies",
                  file=sys.stderr)
        env = dict(os.environ, R6_TIMINGS="1")
        if runtime_staged is not None:
            env["R6_RUNTIME_DIR"] = str(runtime_staged)
        staged = stage(programs, scratch, "corpus")
        selfhost_staged = stage([selfhost_ir], scratch, "selfhost")[0]
        corpus, corpus_pipeline = measure_corpus(staged_r6, staged, scratch, args.reps,
                                                 args.timeout, env)
        selfhost_r6, selfhost_pipeline = measure_selfhost_r6(staged_r6, selfhost_staged, scratch,
                                                             args.reps, args.timeout, env)
    finally:
        shutil.rmtree(scratch, ignore_errors=True)
    selfhost_wall = measure_selfhost_wall(script, args.orbit_root, args.compiler, r6,
                                          args.wall_reps, args.timeout)

    record = {
        "corpusPrograms": len(programs),
        "corpusTotalMs": round(corpus, 1),
        "corpusPipelineMs": round(corpus_pipeline, 1),
        "selfhostR6Ms": round(selfhost_r6, 1),
        "selfhostPipelineMs": round(selfhost_pipeline, 1),
        "selfhostWallMs": round(selfhost_wall, 1),
        "reps": args.reps,
        "wallReps": args.wall_reps,
    }
    print(f"\ncorpus total     {record['corpusTotalMs']:9.1f} ms  "
          f"({len(programs)} programs, link included)")
    print(f"corpus in R6     {record['corpusPipelineMs']:9.1f} ms  "
          f"(load, codegen, peephole, regalloc, asm, object)")
    print(f"self-host R6     {record['selfhostR6Ms']:9.1f} ms  (link included)")
    print(f"self-host in R6  {record['selfhostPipelineMs']:9.1f} ms")
    print(f"self-host wall   {record['selfhostWallMs']:9.1f} ms  "
          f"(fixed point and the built compiler included)")

    if args.json:
        Path(args.json).write_text(json.dumps(record, indent=2) + "\n", encoding="utf-8")

    baseline_path = Path(args.baseline).resolve()
    baseline = load_baseline(baseline_path)
    if args.write_baseline:
        entry = dict(record, date=time.strftime("%Y-%m-%d"),
                     tolerance=args.tolerance)
        baseline.setdefault("platforms", {})[key] = entry
        baseline_path.parent.mkdir(parents=True, exist_ok=True)
        baseline_path.write_text(json.dumps(baseline, indent=2) + "\n", encoding="utf-8")
        print(f"wrote {baseline_path} ({key})")
    if args.check:
        was = baseline.get("platforms", {}).get(key)
        if not was:
            print(f"no baseline for {key} in {baseline_path}", file=sys.stderr)
            return 2
        findings = compare(record, was, args.tolerance)
        for finding in findings:
            print(f"REGRESSION: {finding}", file=sys.stderr)
        if findings:
            return 1
        print(f"ratchet holds against {baseline_path} ({key}, "
              f"tolerance {args.tolerance:.0%})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
